// Helper functions
export function getArticlesByCategory(category: string): Article[] {
  return initialArticles.filter(article => article.category === category);
}

export function getArticleBySlug(slug: string): Article | undefined {
  return initialArticles.find(article => article.slug === slug);
}

export function getLatestArticles(count: number = 5): Article[] {
  return [...initialArticles]
    .sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime())
    .slice(0, count);
}

export function getPopularArticles(count: number = 5): Article[] {
  return [...initialArticles]
    .sort((a, b) => b.views - a.views)
    .slice(0, count);
}

export function getAllCategories(): string[] {
  return [...new Set(initialArticles.map(article => article.category))];
}

export function searchArticles(query: string): Article[] {
  const lowercaseQuery = query.toLowerCase();
  return initialArticles.filter(article => 
    article.title.toLowerCase().includes(lowercaseQuery) ||
    article.excerpt.toLowerCase().includes(lowercaseQuery) ||
    article.tags.some(tag => tag.toLowerCase().includes(lowercaseQuery))
  );
}
